// Generates src/lib/currency/currencies.data.ts from the official ISO 4217 list.
// Usage: npm run gen:currencies [-- path/to/list-one.xml]
// Without a path, the list is downloaded from SIX (the ISO 4217 maintenance agency).
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ISO_URL =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/lib/currency/currencies.data.ts');

// Symbols chosen in the design handoff (Phone.dc.html CUR table). They win over Intl.
const DESIGN_SYMBOLS = {
  AUD: '$',
  JPY: '¥',
  TWD: 'NT$',
  NZD: 'NZ$',
  USD: 'US$',
  EUR: '€',
  GBP: '£',
  CAD: 'C$',
  CHF: 'CHF ',
  CNY: 'CN¥',
  HKD: 'HK$',
  KRW: '₩',
  SGD: 'S$',
  THB: '฿',
  VND: '₫',
  AED: 'AED ',
};

// Names used in the design handoff (CUR / CUR_ZH tables). They win over Intl.
const DESIGN_EN = {
  GBP: 'Pound Sterling',
  CNY: 'Chinese Yuan',
  AED: 'UAE Dirham',
};
const DESIGN_ZH = {
  AUD: '澳幣',
  JPY: '日圓',
  TWD: '新台幣',
  NZD: '紐西蘭幣',
  USD: '美元',
  EUR: '歐元',
  GBP: '英鎊',
  CAD: '加拿大幣',
  CHF: '瑞士法郎',
  CNY: '人民幣',
  HKD: '港幣',
  KRW: '韓元',
  SGD: '新加坡幣',
  THB: '泰銖',
  VND: '越南盾',
  AED: '阿聯酋迪拉姆',
};

const xml = process.argv[2] ? await readFile(process.argv[2], 'utf8') : await (await fetch(ISO_URL)).text();
const published = /Pblshd="([^"]+)"/.exec(xml)?.[1] ?? 'unknown';

const entries = new Map();
for (const [, body] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(body)?.[1];
  const units = /<CcyMnrUnts>(\d+)<\/CcyMnrUnts>/.exec(body)?.[1];
  const isoName = /<CcyNm[^>]*>([^<]+)<\/CcyNm>/.exec(body)?.[1];
  const isFund = /<CcyNm IsFund="true"/.test(body);
  // Skip funds, precious metals and testing codes (no minor units, or X-codes).
  if (!code || units === undefined || isFund || code.startsWith('X')) continue;
  if (!entries.has(code)) entries.set(code, { code, minorUnits: Number(units), isoName });
}

const en = new Intl.DisplayNames(['en-AU'], { type: 'currency' });
const zh = new Intl.DisplayNames(['zh-TW'], { type: 'currency' });
const symbolOf = (code) => {
  if (DESIGN_SYMBOLS[code]) return DESIGN_SYMBOLS[code];
  const part = new Intl.NumberFormat('en', { style: 'currency', currency: code })
    .formatToParts(0)
    .find((p) => p.type === 'currency')?.value;
  return !part || part === code ? `${code} ` : part;
};

const rows = [...entries.values()]
  .sort((a, b) => a.code.localeCompare(b.code))
  .map(({ code, minorUnits, isoName }) => {
    const nameEn = DESIGN_EN[code] ?? en.of(code) ?? isoName;
    const nameZh = DESIGN_ZH[code] ?? zh.of(code) ?? nameEn;
    return `  ${code}: { code: '${code}', minorUnits: ${minorUnits}, symbol: ${JSON.stringify(symbolOf(code))}, nameEn: ${JSON.stringify(nameEn)}, nameZh: ${JSON.stringify(nameZh)} },`;
  });

const out = `// Generated by scripts/generate-currencies.mjs from ISO 4217 list one (published ${published}).
// Do not edit by hand; re-run \`npm run gen:currencies\`.
import type { CurrencyInfo } from './types';

export const ISO_PUBLISHED = '${published}';

export const CURRENCIES: Record<string, CurrencyInfo> = {
${rows.join('\n')}
};
`;
await writeFile(OUT, out);
console.log(`Wrote ${rows.length} currencies (ISO list ${published}) to ${OUT}`);
